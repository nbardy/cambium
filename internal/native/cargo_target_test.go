const cargoFixtureLock = `# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "app"
version = "0.1.0"
dependencies = [
 "lib-a",
 "serde",
]

[[package]]
name = "lib-a"
version = "0.1.0"

[[package]]
name = "serde"
version = "1.0.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "00"

[[package]]
name = "gitdep"
version = "0.2.0"
source = "git+https://example.test/gitdep#abc"
`

func writeCargoFixture(t *testing.T, root string, files ...string) {
	t.Helper()
	for _, relative := range files {
		path := filepath.Join(root, filepath.FromSlash(relative))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(relative), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

func listFiles(t *testing.T, root string) []string {
	t.Helper()
	var files []string
	err := filepath.WalkDir(root, func(path string, entry fs.DirEntry, err error) error {
		if err != nil || entry.IsDir() {
			return err
		}
		relative, err := filepath.Rel(root, path)
		files = append(files, filepath.ToSlash(relative))
		return err
	})
	if err != nil {
		t.Fatal(err)
	}
	slices.Sort(files)
	return files
}

// A kept local fingerprint is the bug this mode exists to prevent: Cargo would
// call that crate fresh and run code compiled in another checkout. Everything
// outside Cargo's compile cache is a project's own output and must not travel.
func TestPruneCargoTargetKeepsOnlyThirdPartyCompileCache(t *testing.T) {
	target := filepath.Join(t.TempDir(), "target")
	writeCargoFixture(t, target,
		".rustc_info.json", "CACHEDIR.TAG", "frames/shot.png", "quick-plan-metadata.json", "nextest/archive",
		"debug/.cargo-lock", "debug/app", "debug/app.d", "debug/examples/demo", "debug/incremental/app-1/state",
		"debug/deps/libserde-0123456789abcdef.rlib", "debug/deps/libapp-1111111111111111.rlib",
		"debug/build/serde-2222222222222222/out/gen.rs",
		"debug/.fingerprint/serde-0123456789abcdef/lib-serde.json",
		"debug/.fingerprint/gitdep-3333333333333333/lib-gitdep.json",
		"debug/.fingerprint/app-1111111111111111/bin-app.json",
		"debug/.fingerprint/lib-a-4444444444444444/lib-lib_a.json",
		"debug/.fingerprint/unattributed/lib.json",
		"wasm32-unknown-unknown/stray.txt",
		"wasm32-unknown-unknown/release/app.wasm",
		"wasm32-unknown-unknown/release/deps/serde-5555555555555555.wasm",
		"wasm32-unknown-unknown/release/.fingerprint/serde-5555555555555555/lib-serde.json",
		"wasm32-unknown-unknown/release/.fingerprint/lib-a-6666666666666666/lib-lib_a.json",
	)
	lock := filepath.Join(filepath.Dir(target), "Cargo.lock")
	if err := os.WriteFile(lock, []byte(cargoFixtureLock), 0o644); err != nil {
		t.Fatal(err)
	}
	if got := cargoLockfile(target); got != lock {
		t.Fatalf("lockfile resolved to %s, want %s", got, lock)
	}
	if err := pruneCargoTarget(target, readCargoLocals(lock)); err != nil {
		t.Fatal(err)
	}
	want := []string{
		".rustc_info.json", "CACHEDIR.TAG",
		"debug/.fingerprint/gitdep-3333333333333333/lib-gitdep.json",
		"debug/.fingerprint/serde-0123456789abcdef/lib-serde.json",
		"debug/build/serde-2222222222222222/out/gen.rs",
		"debug/deps/libapp-1111111111111111.rlib",
		"debug/deps/libserde-0123456789abcdef.rlib",
		"wasm32-unknown-unknown/release/.fingerprint/serde-5555555555555555/lib-serde.json",
		"wasm32-unknown-unknown/release/deps/serde-5555555555555555.wasm",
	}
	slices.Sort(want)
	if got := listFiles(t, target); !slices.Equal(got, want) {
		t.Errorf("pruned target holds\n%v\nwant\n%v", got, want)
	}
}

// Without a lockfile nothing says which packages are local. Keeping any
// fingerprint would then be a guess.
func TestPruneCargoTargetWithoutLockfileKeepsNoFingerprint(t *testing.T) {
	for name, content := range map[string]*string{"missing": nil, "no packages": new(string)} {
		t.Run(name, func(t *testing.T) {
			target := filepath.Join(t.TempDir(), "target")
			writeCargoFixture(t, target, "debug/.fingerprint/serde-0123456789abcdef/lib-serde.json", "debug/deps/libserde-0123456789abcdef.rlib")
			lock := cargoLockfile(target)
			if content != nil {
				if err := os.WriteFile(lock, []byte(*content), 0o644); err != nil {
					t.Fatal(err)
				}
			}
			if err := pruneCargoTarget(target, readCargoLocals(lock)); err != nil {
				t.Fatal(err)
			}
			if got, want := listFiles(t, target), []string{"debug/deps/libserde-0123456789abcdef.rlib"}; !slices.Equal(got, want) {
				t.Errorf("pruned target holds %v, want %v", got, want)
			}
		})
	}
}

// A snapshot taken during a build can pair one unit's new output with
// another's old record. Cargo holds this lock exclusively while it builds.
func TestHoldCargoIdleRefusesARunningBuildAndBlocksANewOne(t *testing.T) {
	target := filepath.Join(t.TempDir(), "target")
	writeCargoFixture(t, target, "debug/.cargo-lock", "debug/.fingerprint/serde-0123456789abcdef/lib-serde.json")
	build, err := os.Open(filepath.Join(target, "debug", ".cargo-lock"))
	if err != nil {
		t.Fatal(err)
	}
	defer build.Close()
	if err := syscall.Flock(int(build.Fd()), syscall.LOCK_EX); err != nil {
		t.Fatal(err)
	}
	if _, err := holdCargoIdle(target); !errors.Is(err, errCargoBusy) {
		t.Fatalf("a running build was not detected: %v", err)
	}
	if err := syscall.Flock(int(build.Fd()), syscall.LOCK_UN); err != nil {
		t.Fatal(err)
	}
	release, err := holdCargoIdle(target)
	if err != nil {
		t.Fatal(err)
	}
	if err := syscall.Flock(int(build.Fd()), syscall.LOCK_EX|syscall.LOCK_NB); !errors.Is(err, syscall.EWOULDBLOCK) {
		t.Errorf("a build could start during the snapshot: %v", err)
	}
	release()
	if err := syscall.Flock(int(build.Fd()), syscall.LOCK_EX|syscall.LOCK_NB); err != nil {
		t.Errorf("the lock was not released: %v", err)
	}
}
